const DICTS: Record<DraftLocale | 'en', Dict> = { en, es, 'pt-BR': ptBR }

export function tt(locale: DraftLocale | 'en', key: TownKey, repl?: Record<string, string | number>): string {
  let s = DICTS[locale][key] ?? en[key]
  if (repl) for (const [k, v] of Object.entries(repl)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}
