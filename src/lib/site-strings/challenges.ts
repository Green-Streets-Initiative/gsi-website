/**
 * The challenge pages in four languages (translation plan, batch 5):
 * /challenges, a creative challenge (/challenges/[slug], /enter, /e/[id],
 * /rules) and a workplace challenge's public rules (/shift/challenge/[id]).
 *
 * Words come from the Shift app where it has them (locales/*.json:
 * employer_challenge.rules for the counting sentences, events.*, grand_prize.*,
 * sweepstakes.*). Challenge names, taglines, briefs, prize names and sponsor
 * names come from the database and stay in English.
 */
import { createElement, Fragment, type ReactNode } from 'react'
import { defineStrings } from '@/lib/site-i18n'

/**
 * A translated sentence with parts that are elements (a link, bold text):
 * `rich(t('voted'), { title: <b>…</b> })`. One template per language, so word
 * order is the translator's; nothing is stitched from fragments.
 */
export function rich(template: string, parts: Record<string, ReactNode>): ReactNode[] {
  return template.split(/(\{\w+\})/).map((piece, i) => {
    const m = piece.match(/^\{(\w+)\}$/)
    const node = m && m[1] in parts ? parts[m[1]] : piece
    return createElement(Fragment, { key: i }, node)
  })
}

