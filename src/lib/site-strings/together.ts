export type TogetherKey = keyof typeof togetherStrings.en

export const WAY_KEY: Record<PartnerWay, TogetherKey> = { bike: 'way.bike', walk: 'way.walk', transit: 'way.transit', micro: 'way.micro' }
export const DAY_KEY: Record<PartnerDay, TogetherKey> = {
  mon: 'day.mon', tue: 'day.tue', wed: 'day.wed', thu: 'day.thu', fri: 'day.fri', sat: 'day.sat', sun: 'day.sun',
}
export const TIME_KEY: Record<PartnerTime, TogetherKey> = { morning: 'time.morning', midday: 'time.midday', evening: 'time.evening' }
export const SLOT_KEY: Record<PracticeSlot, TogetherKey> = {
  weekend_morning: 'slot.weekend_morning', weekend_afternoon: 'slot.weekend_afternoon', weekday_evening: 'slot.weekday_evening',
}
export const ROLE_KEY: Record<CarpoolRole, TogetherKey> = { driver: 'role.driver', rider: 'role.rider', either: 'role.either' }
export const LANGUAGE_KEY: Record<PartnerLanguage, TogetherKey> = {
  en: 'lang.en', es: 'lang.es', pt: 'lang.pt', zh: 'lang.zh', ht: 'lang.ht', vi: 'lang.vi', ar: 'lang.ar', fr: 'lang.fr',
}
const FORM_KEY: Record<'do' | 'does' | 'ing', Record<PartnerWay, TogetherKey>> = {
  do: { bike: 'do.bike', walk: 'do.walk', transit: 'do.transit', micro: 'do.micro' },
  does: { bike: 'does.bike', walk: 'does.walk', transit: 'does.transit', micro: 'does.micro' },
  ing: { bike: 'ing.bike', walk: 'ing.walk', transit: 'ing.transit', micro: 'ing.micro' },
}

/**
 * "a, b or c" in the page's language. English keeps its own form (no comma
 * before "or"); the others use the browser's own list rules.
 */
export function orList(locale: SiteLocale, words: string[]): string {
  if (words.length <= 1) return words.join('')
  if (locale === 'en') return `${words.slice(0, -1).join(', ')} or ${words[words.length - 1]}`
  return new Intl.ListFormat(SITE_LOCALE_TAG[locale], { type: 'disjunction' }).format(words)
}

/** The ways as a verb phrase in the page's language (lib/together waysText, per language). */
export function waysWords(locale: SiteLocale, ways: PartnerWay[], form: 'do' | 'does' | 'ing', t: (k: TogetherKey) => string): string {
  const list: PartnerWay[] = ways.length ? ways : ['bike', 'walk', 'transit']
  return orList(locale, list.map((w) => t(FORM_KEY[form][w])))
}

/** "Weekend mornings", "Weekend mornings or weekday evenings" (lib/together slotsText, per language). */
export function slotWords(locale: SiteLocale, slots: PracticeSlot[], t: (k: TogetherKey) => string): string {
  const order: PracticeSlot[] = ['weekend_morning', 'weekend_afternoon', 'weekday_evening']
  const words = order.filter((s) => slots.includes(s)).map((s, i) => (i === 0 ? t(SLOT_KEY[s]) : t(SLOT_KEY[s]).toLocaleLowerCase(SITE_LOCALE_TAG[locale])))
  return orList(locale, words)
}
