const strings: Record<NearbyLocale, Dict> = {
  en,
  es,
  'pt-BR': ptBR,
  'zh-Hans': zhHans,
}

/**
 * Translate `key` into `locale`, with `{placeholder}` interpolation. Falls back
 * to English, then to the key itself, so nothing ever renders blank.
 */
export function t(
  locale: NearbyLocale,
  key: string,
  replacements?: Record<string, string | number | null | undefined>,
): string {
  let value = strings[locale]?.[key] ?? strings.en[key] ?? key
  if (replacements) {
    for (const [k, v] of Object.entries(replacements)) {
      value = value.split(`{${k}}`).join(v == null ? '' : String(v))
    }
  }
  return value
}

/**
 * Resolve a locale from a `?lang=` param (wins) or an Accept-Language header /
 * `navigator.language` string. Normalizes `pt*`→`pt-BR` and `zh*`→`zh-Hans` so
 * the web matches the app's locale set. Defaults to English.
 */
export function resolveNearbyLocale(
  param?: string | null,
  acceptOrBrowser?: string | null,
): NearbyLocale {
  const norm = (raw: string): NearbyLocale | null => {
    const l = raw.trim().toLowerCase()
    if (!l) return null
    if (l === 'en' || l.startsWith('en-')) return 'en'
    if (l === 'es' || l.startsWith('es-')) return 'es'
    if (l === 'pt' || l.startsWith('pt-') || l.startsWith('pt')) return 'pt-BR'
    if (l === 'zh' || l.startsWith('zh')) return 'zh-Hans'
    return null
  }
  if (param) {
    const m = norm(param)
    if (m) return m
  }
  if (acceptOrBrowser) {
    for (const part of acceptOrBrowser.split(',')) {
      const lang = part.split(';')[0]
      const m = norm(lang)
      if (m) return m
    }
  }
  return 'en'
}
