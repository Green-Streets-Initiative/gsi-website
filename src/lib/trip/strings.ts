const strings: Record<NearbyLocale, Dict> = { en, es, 'pt-BR': ptBR, 'zh-Hans': zhHans }

export function tripT(locale: NearbyLocale, key: string, vars?: Record<string, string | number>): string {
  let value = strings[locale]?.[key] ?? en[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) value = value.split(`{${k}}`).join(String(v))
  return value
}
